#!/usr/bin/env node
/**
 * Convert an eBible.org "verse per line" file (…_vpl.txt) into the app's
 * per-book JSON files.
 *
 *   node scripts/import-vpl.mjs <translation-id> <path/to/xxx_vpl.txt>
 *
 * Output: src/data/bibles/<id>/<BB>.json  — an array of chapters, each an
 * array of verse strings (index 0 = verse 1; "" if a verse is missing),
 * plus src/data/bibles/<id>/index.ts which lazy-loads each book.
 *
 * Only the 66 books in src/bible/books.ts are kept (deuterocanon skipped
 * for now). Chapter counts are checked against books.ts.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const [, , id, file] = process.argv;
if (!id || !file || !/^[a-z0-9-]+$/.test(id)) {
  console.error('usage: node scripts/import-vpl.mjs <translation-id> <file_vpl.txt>');
  process.exit(1);
}

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

// Read book codes and chapter counts from books.ts so there is one source of truth.
const booksSrc = readFileSync(join(root, 'src/bible/books.ts'), 'utf8');
const books = [...booksSrc.matchAll(/\['([0-9A-Z]{3})', '[^']+', (\d+),/g)].map((m, i) => ({
  id: i + 1,
  code: m[1],
  chapters: Number(m[2]),
}));
if (books.length !== 66) throw new Error(`expected 66 books in books.ts, found ${books.length}`);
const byCode = new Map(books.map((b) => [b.code, b]));

/** KJV marks supplied words as [was] and paragraphs as ¶ — keep plain text for now. */
function clean(text) {
  return text.replace(/¶\s*/g, '').replace(/[[\]]/g, '').replace(/\s+/g, ' ').trim();
}

const data = new Map(); // bookId -> chapters[][]
let kept = 0;
let skipped = 0;
for (const line of readFileSync(file, 'utf8').split(/\r?\n/)) {
  if (!line.trim()) continue;
  const m = line.match(/^(\S{3}) (\d+):(\d+) ?(.*)$/);
  if (!m) throw new Error(`bad line: ${line.slice(0, 80)}`);
  const book = byCode.get(m[1]);
  if (!book) {
    skipped++;
    continue;
  }
  const chapter = Number(m[2]);
  const verse = Number(m[3]);
  const chapters = data.get(book.id) ?? [];
  data.set(book.id, chapters);
  const verses = (chapters[chapter - 1] ??= []);
  verses[verse - 1] = clean(m[4]);
  kept++;
}

const outDir = join(root, 'src/data/bibles', id);
mkdirSync(outDir, { recursive: true });
const problems = [];
for (const book of books) {
  const chapters = data.get(book.id);
  if (!chapters) {
    problems.push(`${book.code}: missing`);
    continue;
  }
  if (chapters.length !== book.chapters) {
    problems.push(`${book.code}: ${chapters.length} chapters, expected ${book.chapters}`);
  }
  const filled = Array.from({ length: chapters.length }, (_, c) =>
    Array.from({ length: chapters[c]?.length ?? 0 }, (_, v) => chapters[c][v] ?? ''),
  );
  writeFileSync(join(outDir, `${String(book.id).padStart(2, '0')}.json`), JSON.stringify(filled));
}
if (problems.length) {
  console.error(problems.join('\n'));
  process.exit(1);
}

const loaders = books
  .map((b) => {
    const n = String(b.id).padStart(2, '0');
    return `  ${b.id}: () => import('./${n}.json').then((m) => m.default as BookText),`;
  })
  .join('\n');
writeFileSync(
  join(outDir, 'index.ts'),
  `// Generated by scripts/import-vpl.mjs — do not edit.\n` +
    `import type { BookLoaders, BookText } from '@/bible/types';\n\n` +
    `const loaders: BookLoaders = {\n${loaders}\n};\n\nexport default loaders;\n`,
);

console.log(`${id}: ${kept} verses in 66 books written to ${outDir} (${skipped} other-book verses skipped)`);
